COLOR_RE = re.compile(r'穿.+?(?:色|衣物)(?:以稳气场)?$')


def rewrite(text, mapping):
    core = COLOR_RE.sub('', text)
    return mapping.get(core, core)


def main():
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)

    unmatched = []
    for e in data:
        for v in e.get('variants', []):
            v['yi'] = rewrite(v['yi'], YI_NEW)
            v['ji'] = rewrite(v['ji'], JI_NEW)
            if v['yi'] not in YI_NEW.values():
                unmatched.append(('yi', e['hexagram_name'], v['variant'], v['yi']))
            if v['ji'] not in JI_NEW.values():
                unmatched.append(('ji', e['hexagram_name'], v['variant'], v['ji']))

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print('重写完成，卦数:', len(data))
    if unmatched:
        print('!! 未匹配项:')
        for u in unmatched[:10]:
            print('  ', u)
    else:
        print('全部匹配 ✓')


if __name__ == '__main__':
    main()
